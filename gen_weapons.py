"""Generate weapons.txt: one haptic pattern per weapon/skill (and per combo strike) from the game's own data.
Feel comes from item category + tags; strength/length from each strike's power, wind-up and recovery.
Edit weapons.txt by hand afterwards if you like; only re-run this to reset it.
"""
import json, math, os, re
import pak

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.join(HERE, "..")

# hand-made signatures; strikes split by '|', steps are lo,hi,ms (0-255). '>' = sweeps toward facing side
OVERRIDES = {
    "FlameThrower":   "60,140,40 90,90,40",                                   # Fire Blast: held roar, re-fires
    "ThrowingKnife":  "0,200,18 0,60,25",                                     # tiny flick
    "BehemothHammer": "255,180,60 255,60,140 140,0,160 60,0,140",             # Flint: ground-shaking slam
    "StunMace":       "200,120,50 120,40,90 | 210,120,50 130,40,90 | 255,200,70 200,60,120 80,0,120",
    "BroadSword":     "> 140,200,70 120,60,110 | > 150,210,80 130,60,120 | 255,255,90 200,80,140 80,0,140",
    "DualDaggers":    "> 0,170,22 | > 0,190,22 | > 60,230,30 30,80,40",
    "Whip":           "> 0,120,30 0,255,25",                                  # crack at the tip
    "KingScepter":    "200,255,40 140,140,70 70,70,120",                      # royal gong; spin/stop are separate events
    "Pan":           "220,255,35 40,40,60 | 220,255,35 40,40,60 | 220,255,35 40,40,60 | 255,255,45 120,120,90",
}

SKILL_SHAPES = {  # item group -> pattern
    0: "230,80,50 0,0,40 160,60,60",        # turrets / traps: deploy clunk
    1: "20,160,70 0,60,60",                 # grenades: throw whoosh
    2: "230,80,50 0,0,40 160,60,60",
    3: "120,120,110 60,160,120",            # powers
}


def english_names():
    pot = open(os.path.join(GAME, "lang", "main-en.pot"), encoding="utf8").read()
    en = {}
    for block in pot.split("\n\n"):
        m = re.search(r'^msgid "(.*)"$', block, re.M)
        if m:
            for ref in re.findall(r"res/data\.cdb:item/#(\d+)\.name", block):
                en[int(ref)] = m.group(1)
    return en


def pw(s):
    p = s.get("power") or 20
    return p[0] if isinstance(p, list) else p


def clamp(v, a, b):
    return max(a, min(b, v))


def strike_pattern(cat, s, last, multi):
    power = pw(s)
    lo_p, hi_p = (8, 250) if cat.startswith("melee") else (5, 120)
    i = 0.25 + 0.75 * math.log(clamp(power, lo_p, hi_p) / lo_p) / math.log(hi_p / lo_p)
    if last and multi:
        i = min(1.0, i + 0.15)  # combo finisher hits harder
    dur = clamp(int(40 + 250 * (s.get("lockCtrlAfter") or 0) + 60 * (s.get("charge") or 0)), 40, 300)
    held = s.get("dynamicCharge") == 1
    q = lambda lo, hi, ms: f"{int(255 * clamp(lo * i, 0, 1))},{int(255 * clamp(hi * i, 0, 1))},{int(ms)}"
    if held:  # continuous weapons re-fire fast: keep each burst short
        return q(0.4, 0.6, 50)
    if cat == "melee_light":
        return "> " + " ".join([q(0.3, 1.0, dur * 0.5), q(0.1, 0.4, dur * 0.5)])
    if cat == "melee":
        return "> " + " ".join([q(0.6, 0.9, dur * 0.5), q(0.4, 0.3, dur * 0.5)])
    if cat == "melee_heavy":
        return " ".join([q(1.0, 0.7, dur * 0.4), q(0.8, 0.2, dur * 0.4), q(0.3, 0, dur * 0.4)])
    if cat == "shield":
        return " ".join([q(0.9, 0.4, 70), q(0.3, 0, 80)])
    if cat == "crossbow":
        return " ".join([q(0.7, 1.0, 50), q(0.5, 0.2, dur)])
    if cat == "explosive":
        return " ".join([q(0.6, 1.0, 40), q(1.0, 0.5, 80), q(0.6, 0.2, 120)])
    if cat == "rapid":
        return q(0.2, 0.7, 30)
    return " ".join([q(0.2, 1.0, 30), q(0.5, 0.3, dur)])  # bows, guns, throwables


def category(item, tags, strikes):
    g = item.get("group")
    if g == 6: return "shield"
    if g == 5:
        if "Explosive" in tags: return "explosive"
        if "IsCrossbow" in tags or "HeavyWeapon" in tags: return "crossbow"
        if "RapidFire" in tags: return "rapid"
        return "ranged"
    if "HeavyWeapon" in tags: return "melee_heavy"
    avg = sum(pw(s) for s in strikes) / max(1, len(strikes))
    fast = all((s.get("charge") or 0) < 0.25 for s in strikes)
    return "melee_light" if fast and avg < 60 else "melee"


def main():
    cdb = json.loads(pak.read(os.path.join(GAME, "res.pak"), "data.cdb"))
    sh = {s["name"]: s for s in cdb["sheets"]}
    en = english_names()
    weapons = {w["item"]: w for w in sh["weapon"]["lines"]}
    lines = ["# id [>] strike1 | strike2 | ...   strike = steps 'lo,hi,ms' (0-255 motor, ms). '>' sweeps toward facing.",
             "# Generated by gen_weapons.py from game data; edit freely. Changes apply on next game launch."]
    for idx, item in enumerate(sh["item"]["lines"]):
        iid, name = item["id"], en.get(idx, "?")
        tags = {t.get("tag") for t in item.get("tags", [])}
        if iid in OVERRIDES:
            pat, cat = OVERRIDES[iid], "custom"
        elif iid in weapons and weapons[iid]["strikeChain"]:
            st = weapons[iid]["strikeChain"]
            cat = category(item, tags, st)
            pat = " | ".join(strike_pattern(cat, s, k == len(st) - 1, len(st) > 1) for k, s in enumerate(st))
        elif item.get("group") in SKILL_SHAPES:
            pat, cat = SKILL_SHAPES[item["group"]], "skill"
        else:
            continue
        lines.append(f"{iid} {pat}    # {name} ({cat})")
    open(os.path.join(HERE, "weapons.txt"), "w", encoding="utf8").write("\n".join(lines) + "\n")
    print(f"wrote {len(lines) - 2} patterns")


if __name__ == "__main__":
    main()
